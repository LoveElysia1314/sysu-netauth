#!/usr/bin/env python3
"""Generate shared SVG and Swift geometry, and verify committed Windows ICO provenance.
No third-party dependencies. Run from any directory; see assets/icons/README.md.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/icons/source.json'
GENERATED = ROOT / 'assets/icons/generated'
SWIFT = ROOT / 'macos/Sources/NetAuthArtwork/GeneratedIconSource.swift'
SIZES = [16, 20, 24, 32, 40, 48, 64, 128, 256]

def digest(data): return hashlib.sha256(data).hexdigest()

def source_bytes(): return SOURCE.read_text(encoding='utf-8').encode('utf-8')

def outputs():
    raw = SOURCE.read_text(encoding='utf-8')
    spec = json.loads(raw)
    assert spec['schema'] == 1 and spec['size'] == 18
    assert set(spec['states']) == {'ready', 'authenticating', 'authenticated', 'failed', 'disconnected', 'unavailable'}
    def svg_path(path):
        parts = []
        for c in path['commands']:
            assert len(c) == {0:3, 1:3, 2:7, 3:1, 4:5}[c[0]]
            if c[0] == 4:
                _, x, y, w, h = c
                return f'<ellipse cx="{x+w/2:g}" cy="{y+h/2:g}" rx="{w/2:g}" ry="{h/2:g}" fill="currentColor"/>'
            parts.append(['M','L','C','Z'][c[0]] + ' '.join(f'{v:g}' for v in c[1:]))
        return f'<path d="{" ".join(parts)}" stroke="currentColor" stroke-width="{path["width"]:g}" fill="none"/>'
    result = {SWIFT: '// Generated by scripts/generate-icons.py; edit assets/icons/source.json.\nimport Foundation\nenum GeneratedIconSource {\n    static let sourceSHA256 = "' + digest(source_bytes()) + '"\n    static let json = #"""\n' + raw.rstrip() + '\n"""#\n}\n'}
    for name, mark in {**spec['states'], 'app': {'color':'green','paths':spec['states']['ready']['paths']}}.items():
        color = spec['palette'][mark['color']]
        svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 18 18">\n'
               '<!-- Generated from assets/icons/source.json; y-up geometry is shared with AppKit. -->\n'
               '<g transform="translate(0 18) scale(1 -1)" stroke-linecap="round" stroke-linejoin="round">\n'
               f'<g color="#{spec["windows_outline"]}">{svg_path(spec["shield"])}</g>\n'
               f'<g color="#{color}">' + ''.join(svg_path(p) for p in mark['paths']) + '</g>\n</g>\n</svg>\n')
        result[GENERATED / 'svg' / f'{name}.svg'] = svg
    return result

def windows_manifest():
    return {'source_sha256': digest(source_bytes()), 'sizes': SIZES,
            'files': {p.name: digest(p.read_bytes()) for p in sorted((GENERATED/'windows').glob('*.ico'))}}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--record-windows', action='store_true')
    args = parser.parse_args()
    generated = outputs()
    manifest = GENERATED / 'windows/manifest.json'
    stamp = GENERATED / 'windows/source.sha256'
    if args.record_windows:
        assert stamp.read_text().strip() == digest(source_bytes()), 'Windows export used stale compiled geometry; rebuild and re-export'
        value = windows_manifest()
        assert set(value['files']) == {f'{n}.ico' for n in ['app','ready','authenticating','authenticated','failed','disconnected','unavailable']}
        manifest.write_text(json.dumps(value,indent=2)+'\n', encoding='utf-8')
    elif args.check:
        for path, text in generated.items():
            assert path.exists() and path.read_text(encoding='utf-8') == text, f'Stale generated asset: {path.relative_to(ROOT)}'
        assert stamp.read_text().strip() == digest(source_bytes()), 'Stale Windows export source stamp'
        assert manifest.exists() and json.loads(manifest.read_text(encoding='utf-8')) == windows_manifest(), 'Windows icons are stale; regenerate and record provenance'
        print('Shared SVG, Swift geometry and Windows ICO manifest are current')
    else:
        for path, text in generated.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8')
        print('Generated shared SVG and Swift geometry')

if __name__ == '__main__': main()
